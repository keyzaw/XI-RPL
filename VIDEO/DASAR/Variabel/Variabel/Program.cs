// Variabel, Tipe Data, dan Operator Sederhana

int umur = 17; // bentuk Variabel di C#

String // Tipe Data yang menentukan sebuah Variabel
    nama = "eca";

// Integer, yaitu angka bulat
int tahun = 2010;

// Double atau Float, yaitu angka decimal
double tinggi = 170.5;

// Char, yaitu satu karakter huruf
char nilai = 'A';

// String, yaitu kumpulan dari karakter huruf, angka, symbol
String alamat = "Sidoarjo, Candi, Jawa Timur";

// Bool (boolean), yaitu variabel yang terdiri dari dua nilai antara true atu false
bool gemarMembaca = true;
bool sudahMakan = false;

// Operator Sederhana
// Variabel
int a = 12;
int b = 5;

// Penjumlahkan (ada dua cara)
// Cara 1, membuat variabel terlebih dahulu
int hasilPenjumlahan = a + b;
Console.WriteLine(hasilPenjumlahan);

// Cara 2, langsung menulis di dalam Writeline
Console.WriteLine(a + b);

// pengurangan
Console.WriteLine(a - b);

// perkalian
Console.WriteLine(a * b);

// pembagian
Console.WriteLine(a / b);

double c = 12;
double d = 7;

Console.WriteLine(c / d);